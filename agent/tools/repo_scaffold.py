"""Deterministic files laid down when a connected repository is brand new.

Shipped as constants rather than generated by the model: a first commit should
be predictable, reviewable, and identical for every customer.
"""

README = """# Infrastructure

Terraform in this repository is generated by the AEGIS AWS Provisioning
Agent and delivered as a pull request for review.

## Layout

```
modules/<workload>/      reusable module per workload (one per provisioning task)
environments/dev/        the root module: providers, module calls, variables
```

`terraform` commands run inside an environment directory, for example:

```
cd environments/dev
terraform init
terraform plan
```

This layout was created automatically because the repository was empty. Move or
restructure it freely — the agent reads the repository before each change and
follows whatever convention it finds.
"""

# Deliberately does NOT ignore *.tfvars. The agent commits terraform.tfvars as
# example values, and a repo-level ignore would silently drop it from the commit,
# leaving a configuration that references variables it never supplies.
GITIGNORE = """# Terraform state — never commit; it can contain resource attributes and secrets
*.tfstate
*.tfstate.*

# Provider plugins and lock metadata for the local working directory
.terraform/

# Saved plans — binary, and can contain variable values including secrets
tfplan
*.tfplan

crash.log
crash.*.log

# Local overrides and credentials
*.auto.tfvars
override.tf
override.tf.json
*_override.tf
*_override.tf.json
.env
"""

# (path, content, commit message) — order matters: the first PUT is what creates
# the default branch on an empty repository.
BOOTSTRAP_FILES = (
    ("README.md", README, "Initial commit: add README"),
    (".gitignore", GITIGNORE, "Add Terraform .gitignore"),
)
